package practica.jdbc.config;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public class InicializacionBD {

    private static final Logger log = LogManager.getLogger(InicializacionBD.class);

    private final ConexionBD conexionBD;
    private final ConfiguracionBD configuracionBD;

    public InicializacionBD(ConexionBD conexionBD, ConfiguracionBD configuracionBD) {
        this.conexionBD = conexionBD;
        this.configuracionBD = configuracionBD;
    }

    private boolean esMySQL() {
        return "MYSQL".equals(configuracionBD.obtener("database.engine"));
    }

    private String obtenerAutoincremento() {
        if (esMySQL()) {
            return "AUTO_INCREMENT";
        }

        return "GENERATED BY DEFAULT AS IDENTITY";
    }

    public void inicializar() throws SQLException {

        String autoincremento = obtenerAutoincremento();

        String[] tablas = {
                "movimiento_stock",
                "inventario",
                "linea_pedido",
                "pago",
                "pedido",
                "direccion",
                "cliente",
                "vinilo",
                "album_artista",
                "album",
                "artista",
                "genero"
        };

        String[] sentencias = {
                """
                CREATE TABLE genero (
                    id_genero INT %s,
                    nombre VARCHAR(50) NOT NULL,
                    descripcion VARCHAR(255),
                    PRIMARY KEY (id_genero),
                    UNIQUE (nombre)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE artista (
                    id_artista INT %s,
                    nombre VARCHAR(100) NOT NULL,
                    pais_origen VARCHAR(60),
                    PRIMARY KEY (id_artista),
                    UNIQUE (nombre)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE album (
                    id_album INT %s,
                    nombre VARCHAR(150) NOT NULL,
                    anio_lanzamiento INT,
                    id_genero INT NOT NULL,
                    PRIMARY KEY (id_album),
                    FOREIGN KEY (id_genero) REFERENCES genero(id_genero)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE album_artista (
                    id_album INT NOT NULL,
                    id_artista INT NOT NULL,
                    PRIMARY KEY (id_album, id_artista),
                    FOREIGN KEY (id_album) REFERENCES album(id_album),
                    FOREIGN KEY (id_artista) REFERENCES artista(id_artista)
                )
                """,

                """
                CREATE TABLE vinilo (
                    id_vinilo INT %s,
                    id_album INT NOT NULL,
                    referencia VARCHAR(30) NOT NULL,
                    color VARCHAR(30) NOT NULL,
                    precio DECIMAL(8,2) NOT NULL,
                    activo BOOLEAN NOT NULL DEFAULT TRUE,
                    PRIMARY KEY (id_vinilo),
                    UNIQUE (referencia),
                    FOREIGN KEY (id_album) REFERENCES album(id_album),
                    CHECK (precio > 0)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE cliente (
                    id_cliente INT %s,
                    nombre VARCHAR(100) NOT NULL,
                    apellidos VARCHAR(150) NOT NULL,
                    email VARCHAR(150) NOT NULL,
                    telefono VARCHAR(20),
                    PRIMARY KEY (id_cliente),
                    UNIQUE (email)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE direccion (
                    id_direccion INT %s,
                    id_cliente INT NOT NULL,
                    calle VARCHAR(150) NOT NULL,
                    numero VARCHAR(10) NOT NULL,
                    codigo_postal VARCHAR(12) NOT NULL,
                    ciudad VARCHAR(80) NOT NULL,
                    provincia VARCHAR(80),
                    pais VARCHAR(60) NOT NULL,
                    PRIMARY KEY (id_direccion),
                    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE pedido (
                    id_pedido INT %s,
                    id_cliente INT NOT NULL,
                    id_direccion INT NOT NULL,
                    fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    estado VARCHAR(20) NOT NULL,
                    total DECIMAL(8,2) NOT NULL,
                    PRIMARY KEY (id_pedido),
                    FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
                    FOREIGN KEY (id_direccion) REFERENCES direccion(id_direccion),
                    CHECK (estado IN ('PENDIENTE', 'PAGADO', 'CANCELADO')),
                    CHECK (total >= 0)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE pago (
                    id_pago INT %s,
                    id_pedido INT NOT NULL,
                    metodo VARCHAR(20) NOT NULL,
                    fecha_pago TIMESTAMP,
                    importe DECIMAL(8,2) NOT NULL,
                    estado VARCHAR(20) NOT NULL,
                    PRIMARY KEY (id_pago),
                    UNIQUE (id_pedido),
                    FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
                    CHECK (metodo IN ('TARJETA', 'PAYPAL', 'TRANSFERENCIA')),
                    CHECK (estado IN ('PENDIENTE', 'COMPLETADO', 'RECHAZADO', 'REEMBOLSADO')),
                    CHECK (importe > 0)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE linea_pedido (
                    id_linea INT %s,
                    id_pedido INT NOT NULL,
                    id_vinilo INT NOT NULL,
                    cantidad INT NOT NULL,
                    precio_unitario DECIMAL(8,2) NOT NULL,
                    PRIMARY KEY (id_linea),
                    UNIQUE (id_pedido, id_vinilo),
                    FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
                    FOREIGN KEY (id_vinilo) REFERENCES vinilo(id_vinilo),
                    CHECK (cantidad > 0),
                    CHECK (precio_unitario > 0)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE inventario (
                    id_inventario INT %s,
                    id_vinilo INT NOT NULL,
                    stock_actual INT NOT NULL DEFAULT 0,
                    stock_minimo INT NOT NULL DEFAULT 3,
                    control_stock BOOLEAN NOT NULL DEFAULT TRUE,
                    PRIMARY KEY (id_inventario),
                    UNIQUE (id_vinilo),
                    FOREIGN KEY (id_vinilo) REFERENCES vinilo(id_vinilo),
                    CHECK (stock_actual >= 0)
                )
                """.formatted(autoincremento),

                """
                CREATE TABLE movimiento_stock (
                    id_movimiento INT %s,
                    id_vinilo INT NOT NULL,
                    tipo VARCHAR(10) NOT NULL,
                    cantidad INT NOT NULL,
                    fecha_movimiento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    motivo VARCHAR(150) NOT NULL,
                    PRIMARY KEY (id_movimiento),
                    FOREIGN KEY (id_vinilo) REFERENCES vinilo(id_vinilo),
                    CHECK (tipo IN ('ENTRADA', 'SALIDA')),
                    CHECK (cantidad > 0)
                )
                """.formatted(autoincremento)
        };

        String procedimiento = """
                CREATE PROCEDURE resumen_cliente(
                    IN p_id_cliente INT,
                    OUT p_num_pedidos INT,
                    OUT p_total_gastado DECIMAL(10,2))
                BEGIN
                    SELECT COUNT(*), COALESCE(SUM(total), 0)
                    INTO p_num_pedidos, p_total_gastado
                    FROM pedido
                    WHERE id_cliente = p_id_cliente AND estado <> 'CANCELADO';
                END
                """;

        try (Connection conexion = conexionBD.obtenerConexion();
             Statement sentencia = conexion.createStatement()) {

            if (esMySQL()) {
                sentencia.executeUpdate("DROP PROCEDURE IF EXISTS resumen_cliente");
            }

            for (String tabla : tablas) {
                sentencia.executeUpdate("DROP TABLE IF EXISTS " + tabla);
            }

            for (String sql : sentencias) {
                sentencia.executeUpdate(sql);
            }

            if (esMySQL()) {
                sentencia.executeUpdate(procedimiento);
            }

            log.info("Inicializacion - Estructura creada ({} tablas)", tablas.length);
        }
    }
}